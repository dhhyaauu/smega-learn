<?php

namespace App\Http\Middleware;

use Closure;
use Illuminate\Http\Request;
use Symfony\Component\HttpFoundation\Response;

/**
 * Middleware untuk membatasi akses berdasarkan role user.
 *
 * Penggunaan di route: ->middleware('role:admin')
 *
 * Catatan untuk Orang 4:
 * Middleware ini dibuat untuk kebutuhan halaman pengaturan GPS.
 * Silakan gunakan atau ganti dengan implementasi role Anda sendiri.
 */
class EnsureUserRole
{
    public function handle(Request $request, Closure $next, string ...$roles): Response
    {
        $user = $request->user();

        if (! $user || ! in_array($user->role, $roles, true)) {
            abort(403, 'Anda tidak memiliki akses ke halaman ini.');
        }

        return $next($request);
    }
}
